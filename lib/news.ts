export function formatNewsDate(locale: Locale, date: string) {
  const [year, month, day] = date.split("-").map(Number);

  return new Intl.DateTimeFormat(dateLocales[locale], {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(Date.UTC(year, month - 1, day)));
}
